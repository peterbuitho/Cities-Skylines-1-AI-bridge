"""Aarhus Domkirke as a game model: mesh and facade texture, generated from its real measures.

Brick Gothic, 93 m long with the tower to the west and the choir to the east, transept across,
copper roofs, spire to 96 m. Writes model.obj, diffuse.png and a small lod.png into <out dir>.
The mod's POST /commands/create-asset turns them into a .crp asset.

Model space is the game's: x along the lot (west is -x), y up, z towards the street. Metres.

Use: domkirken.py <out dir>
"""
import math, os, sys

import numpy as np
from PIL import Image, ImageDraw

SIZE = 1024
# Texture bands, each the full width so it can repeat along a wall: (v low, v high) in UV space.
GOTHIC, TOWER, COPPER, BRICK = (0.55, 1.0), (0.20, 0.55), (0.08, 0.20), (0.0, 0.08)
BAY = 6.0            # metres per window bay; the texture holds four bays across
TOWER_FACE = 14.0    # metres per tower face; the texture holds two faces across


class Mesh:
    def __init__(self):
        self.faces = []  # (points, uvs)

    def poly(self, points, uvs, inside):
        """A flat polygon facing away from the point `inside`. Wound clockwise seen from outside."""
        p = [np.array(q, dtype=float) for q in points]
        normal = np.cross(p[1] - p[0], p[2] - p[0])
        if np.dot(normal, sum(p) / len(p) - np.array(inside, dtype=float)) < 0:
            p.reverse()
            uvs = list(reversed(uvs))
        self.faces.append((p, list(uvs)))

    def wall(self, a, b, y0, y1, band, metres_per_u, inside, full_height=None):
        """A vertical wall from (x, z) a to b. The band's height stands for full_height metres."""
        full = full_height or (y1 - y0)
        u = math.dist(a, b) / metres_per_u
        v0 = band[0]
        v1 = band[0] + (band[1] - band[0]) * min(1.0, (y1 - y0) / full)
        self.poly([(a[0], y0, a[1]), (b[0], y0, b[1]), (b[0], y1, b[1]), (a[0], y1, a[1])],
                  [(0, v0), (u, v0), (u, v1), (0, v1)], inside)

    def gabled(self, x0, x1, z0, z1, wall_h, ridge_h, along_x, wall_band=GOTHIC):
        """A hall with a pitched copper roof. The ridge runs along x or along z."""
        inside = ((x0 + x1) / 2, wall_h / 2, (z0 + z1) / 2)
        corners = [(x0, z0), (x1, z0), (x1, z1), (x0, z1)]
        for a, b in zip(corners, corners[1:] + corners[:1]):
            self.wall(a, b, 0, wall_h, wall_band, BAY * 4, inside)
        mid_z, mid_x = (z0 + z1) / 2, (x0 + x1) / 2
        roof_u = lambda length: length / 8.0
        if along_x:
            ridge = [(x0, ridge_h, mid_z), (x1, ridge_h, mid_z)]
            for z in (z0, z1):
                self.poly([(x0, wall_h, z), (x1, wall_h, z), ridge[1], ridge[0]],
                          [(0, COPPER[0]), (roof_u(x1 - x0), COPPER[0]), (roof_u(x1 - x0), COPPER[1]), (0, COPPER[1])], inside)
            for x, r in ((x0, ridge[0]), (x1, ridge[1])):
                self.poly([(x, wall_h, z0), (x, wall_h, z1), r], [(0, BRICK[0]), ((z1 - z0) / 8, BRICK[0]), ((z1 - z0) / 16, BRICK[1])], inside)
        else:
            ridge = [(mid_x, ridge_h, z0), (mid_x, ridge_h, z1)]
            for x in (x0, x1):
                self.poly([(x, wall_h, z0), (x, wall_h, z1), ridge[1], ridge[0]],
                          [(0, COPPER[0]), (roof_u(z1 - z0), COPPER[0]), (roof_u(z1 - z0), COPPER[1]), (0, COPPER[1])], inside)
            for z, r in ((z0, ridge[0]), (z1, ridge[1])):
                self.poly([(x0, wall_h, z), (x1, wall_h, z), r], [(0, BRICK[0]), ((x1 - x0) / 8, BRICK[0]), ((x1 - x0) / 16, BRICK[1])], inside)

    def write(self, path):
        with open(path, "w", encoding="ascii") as f:
            f.write("# generated by tools/landmarks/domkirken.py\n")
            n = 1
            for points, uvs in self.faces:
                normal = np.cross(points[1] - points[0], points[2] - points[0])
                normal = normal / (np.linalg.norm(normal) or 1.0)
                for p, uv in zip(points, uvs):
                    f.write(f"v {p[0]:.3f} {p[1]:.3f} {p[2]:.3f}\nvt {uv[0]:.4f} {uv[1]:.4f}\nvn {normal[0]:.4f} {normal[1]:.4f} {normal[2]:.4f}\n")
                for k in range(1, len(points) - 1):  # fan
                    f.write("f " + " ".join(f"{i}/{i}/{i}" for i in (n, n + k, n + k + 1)) + "\n")
                n += len(points)


def cathedral():
    m = Mesh()
    m.gabled(-32, 28, -11, 11, 18, 30, True)       # nave and aisles
    m.gabled(2, 16, -20, 20, 18, 30, False)        # transept
    m.gabled(28, 44, -8, 8, 18, 27, True)          # choir
    # west tower: brick to 50 m, copper spire to 96 m
    x0, x1, z0, z1, top = -46, -32, -7, 7, 50
    inside = (-39, 25, 0)
    corners = [(x0, z0), (x1, z0), (x1, z1), (x0, z1)]
    for a, b in zip(corners, corners[1:] + corners[:1]):
        m.wall(a, b, 0, top, TOWER, TOWER_FACE * 2, inside)
    apex = (-39, 96, 0)
    for a, b in zip(corners, corners[1:] + corners[:1]):
        m.poly([(a[0], top, a[1]), (b[0], top, b[1]), apex], [(0, COPPER[0]), (1.75, COPPER[0]), (0.875, COPPER[1])], (-39, 60, 0))
    return m


def band_rows(band):
    """Pixel rows of a UV band; row 0 is the top of the image, v = 1."""
    return int(round((1 - band[1]) * SIZE)), int(round((1 - band[0]) * SIZE))


def brick(draw, box, rng, base=(152, 78, 58)):
    x0, y0, x1, y1 = box
    draw.rectangle(box, fill=base)
    course = 5
    for row, y in enumerate(range(y0, y1, course)):
        for x in range(x0 - (row % 2) * 8, x1, 16):
            shade = int(rng.integers(-14, 15))
            draw.rectangle([max(x, x0), y, min(x + 14, x1 - 1), min(y + course - 2, y1 - 1)],
                           fill=tuple(int(np.clip(c + shade, 0, 255)) for c in base))


def pointed_window(draw, cx, bottom, top, half, glass=(38, 44, 60), stone=(196, 186, 168)):
    """A Gothic window: tall, with a pointed arch and stone tracery."""
    spring = top + int(half * 1.5)
    arch = [(cx - half, spring)] + [(cx - half + int(half * (1 - math.cos(t))), spring - int(half * 1.5 * math.sin(t))) for t in np.linspace(0, math.pi / 2, 9)]
    arch += [(cx + half - int(half * (1 - math.cos(t))), spring - int(half * 1.5 * math.sin(t))) for t in np.linspace(math.pi / 2, 0, 9)] + [(cx + half, spring)]
    outline = [(cx - half, bottom)] + arch + [(cx + half, bottom)]
    draw.polygon(outline, fill=glass, outline=stone)
    draw.line(outline + [outline[0]], fill=stone, width=3)
    draw.line([(cx, bottom), (cx, spring - half // 2)], fill=stone, width=2)             # mullion
    for y in range(bottom - 24, spring, -28):
        draw.line([(cx - half, y), (cx + half, y)], fill=(70, 76, 92), width=1)          # glazing bars


def texture():
    rng = np.random.default_rng(1201)  # the cathedral's oldest parts date from about 1200
    img = Image.new("RGB", (SIZE, SIZE))
    d = ImageDraw.Draw(img)

    top, bottom = band_rows(GOTHIC)
    brick(d, (0, top, SIZE, bottom), rng)
    bay = SIZE // 4
    for i in range(4):
        x = i * bay
        d.rectangle([x, top + 14, x + 12, bottom], fill=(120, 60, 46))                   # buttress
        d.rectangle([x + 12, top + 14, x + 15, bottom], fill=(96, 48, 38))               # its shadow
        pointed_window(d, x + bay // 2 + 6, bottom - 70, top + 60, 34)
    d.rectangle([0, bottom - 22, SIZE, bottom], fill=(128, 124, 118))                    # granite plinth
    d.rectangle([0, top, SIZE, top + 14], fill=(176, 104, 82))                           # cornice

    top, bottom = band_rows(TOWER)
    brick(d, (0, top, SIZE, bottom), rng, base=(146, 74, 56))
    face = SIZE // 2
    for i in range(2):
        cx = i * face + face // 2
        for dx in (-70, 70):                                                             # belfry louvres
            pointed_window(d, cx + dx, top + 120, top + 24, 26, glass=(52, 44, 40))
        d.ellipse([cx - 34, top + 140, cx + 34, top + 208], fill=(232, 224, 196), outline=(60, 50, 40), width=4)   # clock
        d.line([(cx, top + 174), (cx, top + 150)], fill=(40, 34, 30), width=3)
        d.line([(cx, top + 174), (cx + 16, top + 180)], fill=(40, 34, 30), width=3)
        for y in (top + 232, top + 282):                                                 # stair slits
            d.rectangle([cx - 5, y, cx + 5, y + 30], fill=(40, 38, 44))
        pointed_window(d, cx, bottom - 6, bottom - 62, 26, glass=(64, 46, 34))           # portal
        d.rectangle([i * face, top, i * face + 10, bottom], fill=(118, 60, 46))          # corner pier
    d.rectangle([0, top, SIZE, top + 8], fill=(176, 104, 82))

    top, bottom = band_rows(COPPER)
    d.rectangle([0, top, SIZE, bottom], fill=(104, 160, 142))                            # verdigris
    for x in range(0, SIZE, 32):
        d.line([(x, top), (x, bottom)], fill=(80, 132, 116), width=2)                    # standing seams
    for y in range(top, bottom, 40):
        d.line([(0, y), (SIZE, y)], fill=(120, 172, 154), width=1)

    top, bottom = band_rows(BRICK)
    brick(d, (0, top, SIZE, bottom), rng)
    return img


def main():
    out = sys.argv[1]
    os.makedirs(out, exist_ok=True)
    mesh = cathedral()
    mesh.write(os.path.join(out, "model.obj"))
    image = texture()
    image.save(os.path.join(out, "diffuse.png"))
    image.resize((128, 128), Image.LANCZOS).save(os.path.join(out, "lod.png"))
    points = np.array([p for face in mesh.faces for p in face[0]])
    print(f"{len(mesh.faces)} faces, {sum(len(f[0]) - 2 for f in mesh.faces)} triangles; "
          f"x {points[:, 0].min():.0f}..{points[:, 0].max():.0f}, height {points[:, 1].max():.0f}, z {points[:, 2].min():.0f}..{points[:, 2].max():.0f}")


if __name__ == "__main__":
    main()
